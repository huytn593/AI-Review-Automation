import {test,expect} from '@playwright/test'

test('create, edit, render and block approval with the real backend',async({page,request},testInfo)=>{
  const errors:string[]=[]
  page.on("pageerror",error=>errors.push(error.message))
  await page.setViewportSize({width:1366,height:768})
  await page.goto('/')
  await expect(page.getByRole('heading',{name:/Create smarter/})).toBeVisible()
  await page.getByLabel('Chủ đề').fill('Review Chromium')
  await page.getByRole('button',{name:'Tạo dự án'}).click()
  await expect(page.getByRole('heading',{name:'Review Chromium'})).toBeVisible()
  await page.getByRole('button',{name:'Thêm nguồn'}).click()
  await page.getByLabel('url',{exact:true}).fill('https://example.com')
  await page.getByLabel('title',{exact:true}).fill('Nguồn thử')
  await page.getByLabel('claim',{exact:true}).fill('Claim thử')
  await page.getByLabel('evidence',{exact:true}).fill('Evidence thử')
  await page.getByRole('button',{name:'Lưu nội dung'}).click()
  await expect(page.locator('#studio > p').filter({hasText:'SCRIPT_READY'})).toBeVisible()
  await page.getByRole('button',{name:'Ollama Draft'}).click()
  await expect(page.getByRole('alert')).toContainText('Không tạo được nháp')
  await page.getByRole('button',{name:'Thêm nguồn'}).click()
  await page.getByRole('button',{name:'Xóa nguồn 2'}).click()
  await page.getByRole('button',{name:'Storyboard',exact:true}).click()
  await page.getByLabel('Lời đọc').fill('Kiểm thử giao diện')
  await page.getByLabel('Phụ đề').fill('Cảnh thử')
  await page.getByRole('button',{name:'Nhân bản'}).click()
  await page.getByLabel('Phụ đề').nth(1).fill('Cảnh thứ hai')
  await page.getByRole('button',{name:'↑ Lên'}).nth(1).click()
  await expect(page.getByLabel('Phụ đề').first()).toHaveValue('Cảnh thứ hai')
  await page.getByRole('button',{name:'Xóa cảnh'}).first().click()
  await page.getByRole('button',{name:'Lưu nội dung'}).click()
  await expect(page.getByRole('status')).toHaveText('Thao tác đã hoàn tất.')
  await page.reload()
  await page.getByRole('button',{name:'Storyboard',exact:true}).click()
  await expect(page.getByLabel('Phụ đề')).toHaveValue('Cảnh thử')
  await page.getByRole('button',{name:'Video Studio',exact:true}).click()
  const queued=page.waitForResponse(response=>response.url().endsWith('/render')&&response.request().method()==='POST')
  await page.getByRole('button',{name:'Render video'}).click()
  expect((await queued).status()).toBe(202)
  await page.reload()
  await expect(page.locator('video')).toBeVisible({timeout:90000})
  const media=await request.get((await page.locator('video').getAttribute('src'))!,{headers:{Range:'bytes=0-63'}})
  expect(media.status()).toBe(206)
  await expect(page.getByRole('heading',{name:/Timeline/})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Track phụ đề'})).toBeVisible()
  await page.getByLabel('Vị trí phát (giây)').focus()
  await page.keyboard.press('ArrowRight')
  await expect.poll(()=>page.locator('video').evaluate(video=>(video as HTMLVideoElement).currentTime)).toBeGreaterThan(0)
  const download=page.waitForEvent('download')
  await page.getByRole('link',{name:'subtitles.srt'}).click()
  expect((await download).suggestedFilename()).toBe('subtitles.srt')
  await page.setViewportSize({width:1920,height:1080})
  await page.screenshot({path:testInfo.outputPath('studio.png'),fullPage:true})
  await page.getByRole('button',{name:'QC',exact:true}).click()
  await expect(page.locator('#studio > p').filter({hasText:'QC_FAILED'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Duyệt bản dựng'})).toBeDisabled()
  const id=await page.getByLabel('Chọn dự án').inputValue()
  const job=await (await request.get('/jobs/'+id)).json()
  const bypass=await request.post('/jobs/'+id+'/approve',{data:{
    render_id:job.render_id,preview_reviewed:true,facts_reviewed:true,rights_reviewed:true,
  }})
  expect(bypass.status()).toBe(409)
  expect(errors).toEqual([])
})

test('production settings persist after browser refresh',async({page})=>{
  await page.goto('/#settings')
  await page.getByLabel('Giọng tiếng Việt').selectOption('vi-VN-NamMinhNeural')
  await page.getByRole('button',{name:'Lưu cấu hình',exact:true}).click()
  await expect(page.getByText('Đã lưu cấu hình.',{exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Giọng tiếng Việt')).toHaveValue('vi-VN-NamMinhNeural')
  await page.getByLabel('Giọng tiếng Việt').selectOption('vi')
  await page.getByRole('button',{name:'Lưu cấu hình',exact:true}).click()
  await expect(page.getByText('Đã lưu cấu hình.',{exact:true})).toBeVisible()
})

test('import authorized media through the library UI',async({page,request},info)=>{
  const {execFileSync}=await import('node:child_process')
  const picture=info.outputPath('original-fixture.png')
  execFileSync('ffmpeg',['-v','error','-f','lavfi','-i','color=c=green:s=32x32','-frames:v','1','-threads','1',picture])
  const response=await request.post('/jobs',{data:{topic:'Media library browser fixture'}})
  expect(response.status()).toBe(201)
  await page.goto('/')
  await page.getByRole('button',{name:'Media',exact:true}).click()
  await page.getByLabel('Tệp media',{exact:true}).setInputFiles(picture)
  await page.getByLabel('Nguồn / chủ sở hữu').fill('Original isolated test fixture')
  await page.getByLabel('Tôi đã kiểm tra quyền sử dụng thương mại',{exact:true}).check()
  await page.getByRole('button',{name:'Nhập và kiểm tra tệp'}).click()
  await expect(page.getByText('Đã nhập media và lưu nguồn/quyền sử dụng.',{exact:true})).toBeVisible()
  await expect(page.getByRole('img',{name:'original-fixture.png',exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('img',{name:'original-fixture.png',exact:true})).toBeVisible()
  await page.locator('#studio').screenshot({path:info.outputPath('media-library.png')})
})
